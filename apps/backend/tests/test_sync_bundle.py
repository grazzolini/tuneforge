def _read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    assert isinstance(payload, dict)
    return payload


def _bundle_files(bundle_root: Path) -> set[str]:
    return {
        path.relative_to(bundle_root).as_posix()
        for path in bundle_root.rglob("*")
        if path.is_file()
    }


def _assert_no_absolute_local_paths(
    payload: dict[str, Any],
    local_roots: Iterable[Path],
) -> None:
    local_root_strings = [str(root) for root in local_roots]
    for value in _iter_strings(payload):
        assert not Path(value).is_absolute(), value
        assert all(root not in value for root in local_root_strings), value


def _assert_no_raw_app_data_entries(payload: dict[str, Any]) -> None:
    forbidden = ("sqlite", ".db", "settings", "appdata", "app-data", "/cache", "\\cache")
    for value in _iter_strings(payload):
        normalized = value.lower()
        assert all(fragment not in normalized for fragment in forbidden), value


def _iter_strings(value: Any) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for child in value.values():
            yield from _iter_strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from _iter_strings(child)


def _write_bytes(path: Path, contents: bytes) -> tuple[str, int]:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(contents)
    content_hash = file_sha256(path)
    assert content_hash is not None
    return content_hash, path.stat().st_size


def _wav_bytes(*, frame_count: int, sample_rate: int = 44100) -> bytes:
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as wav_file:
        wav_file.setnchannels(1)
        wav_file.setsampwidth(2)
        wav_file.setframerate(sample_rate)
        wav_file.writeframes(b"\0\0" * frame_count)
    return buffer.getvalue()
