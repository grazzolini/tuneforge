def test_export_sync_bundle_creates_sync_safe_layout(
    client: object,
    tmp_path: Path,
) -> None:
    bundle_root = tmp_path / "bundle"
    with SessionLocal() as session:
        fixture = _create_project_with_artifacts(session, tmp_path)
        result = export_sync_bundle(
            session,
            bundle_root=bundle_root,
            project_ids=[fixture.project_id],
            provider_device_id="peer-bundle-export",
        )

    metadata = _read_json(bundle_root / "bundle.json")
    manifest_path = bundle_root / "projects" / f"{fixture.project_id}.json"
    manifest = _read_json(manifest_path)
    content_hashes = {
        artifact["content_sha256"]
        for artifact in manifest["artifacts"]
    }
    expected_files = {
        "bundle.json",
        f"projects/{fixture.project_id}.json",
        *{
            f"blobs/sha256/{content_hash[:2]}/{content_hash}"
            for content_hash in content_hashes
        },
    }

    assert result.project_count == 1
    assert result.content_sha256s == sorted(content_hashes)
    assert metadata["kind"] == "tuneforge.sync_bundle"
    assert metadata["version"] == "1"
    assert metadata["project_manifests"] == [
        {
            "content_sha256": file_sha256(manifest_path),
            "path": f"projects/{fixture.project_id}.json",
            "project_id": fixture.project_id,
            "size_bytes": manifest_path.stat().st_size,
        }
    ]
    assert metadata["content_sha256s"] == sorted(content_hashes)
    assert metadata["peer_inventory"] == [
        {
            "device_id": "peer-bundle-export",
            "available_content_sha256": sorted(content_hashes),
        }
    ]
    assert _bundle_files(bundle_root) == expected_files
    _assert_no_absolute_local_paths(metadata, (tmp_path, fixture.root))
    _assert_no_absolute_local_paths(manifest, (tmp_path, fixture.root))
    _assert_no_raw_app_data_entries(metadata)
    _assert_no_raw_app_data_entries(manifest)


