import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const ts = require("typescript");
const root = new URL("../", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("schema/operations-v1.json", root), "utf8"));
const vocabulary = new Set(["$ref", "type", "const", "enum", "oneOf", "anyOf", "properties", "required", "additionalProperties", "items", "description", "title"]);
function type(node) {
  for (const key of Object.keys(node)) assert.ok(vocabulary.has(key), `Unsupported schema keyword: ${key}`);
  if (node.$ref) return node.$ref.split("/").at(-1);
  if ("const" in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(" | ");
  if (node.anyOf || node.oneOf) return (node.anyOf ?? node.oneOf).map(item => `(${type(item)})`).join(" | ");
  if (node.type === "array") return `ReadonlyArray<${type(node.items ?? {})}>`;
  if (node.type === "object") {
    const properties = Object.entries(node.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${node.required?.includes(key) ? "" : "?"}: ${type(value)};`);
    if (node.additionalProperties !== false) properties.push(`[key: string]: ${typeof node.additionalProperties === "object" ? type(node.additionalProperties) : "unknown"};`);
    return `{ ${properties.join(" ")} }`;
  }
  if (node.type === "integer" || node.type === "number") return "number";
  if (["string", "boolean", "null"].includes(node.type)) return node.type;
  assert.equal(node.type, undefined, "Unsupported schema type");
  return "unknown";
}
let source = "// Generated by tools/generate_types.mjs from schema/operations-v1.json.\n";
for (const [name, definition] of Object.entries(schema.$defs)) source += `export type ${name} = ${type(definition)};\n`;
for (const [index, name] of [[0, "OperationRequest"], [1, "OperationResponse"]]) {
  const branches = schema.oneOf[index].oneOf.filter(branch => branch.properties?.operation);
  source += `export type ${name} = ${branches.flatMap(branch => { const operations = branch.properties.operation; return (operations.enum ?? [operations.const]).map(operation => type({ ...branch, properties: { ...branch.properties, operation: { const: operation } } })); }).join(" | ")};\n`;
}
source += `export type Operation = OperationRequest["operation"];
export type Request<O extends Operation> = Omit<Extract<OperationRequest, { operation: O }>, "apiVersion" | "schemaVersion">;
export type Result<O extends Operation> = Extract<OperationResponse, { operation: O }> extends { result: infer R } ? R : never;
`;
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
const output = printer.printFile(ts.createSourceFile("contracts.ts", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS));
const path = new URL("bindings/typescript/contracts.ts", root);
if (process.argv.includes("--check")) assert.equal(readFileSync(path, "utf8"), output, "Generated music-core contract drift");
else { mkdirSync(fileURLToPath(new URL("bindings/typescript/", root)), { recursive: true }); writeFileSync(path, output); }
